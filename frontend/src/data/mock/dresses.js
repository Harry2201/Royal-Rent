function inferGender(dress) {
  if (dress.category === 'Sherwani') return 'men';
  return 'women';
}

/** Canonical listing shape: availability { from, to, status } + gender. */
function normalizeDress(dress) {
  const { available, availableFrom, availableTo, availability, ...rest } = dress;
  const from = availability?.from ?? availableFrom ?? '';
  const to = availability?.to ?? availableTo ?? '';
  const status =
    availability?.status ?? (available === false ? 'booked' : 'available');
  return {
    ...rest,
    designer: dress.designer ?? dress.brand,
    gender: dress.gender ?? inferGender(dress),
    image: dress.image || dress.images?.[0] || '',
    images: dress.images?.length ? dress.images : dress.image ? [dress.image] : [],
    availability: { from, to, status },
  };
}

